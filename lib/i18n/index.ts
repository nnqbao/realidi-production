export function getDictionary(locale: Locale = DEFAULT_LOCALE) {
  return (locale === "en" ? en : vi) as typeof vi;
}

export function t(
  dict: Dict,
  path: string,
  vars?: Record<string, string | number>,
): string {
  const value = path.split(".").reduce<unknown>((acc, key) => {
    if (acc && typeof acc === "object" && key in acc) {
      return (acc as Dict)[key];
    }
    return undefined;
  }, dict);
  if (typeof value !== "string") return path;
  if (!vars) return value;
  return value.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? ""));
}

export function localizeName(
  locale: Locale,
  entity: { name_vi: string; name_en: string },
): string {
  return locale === "en" ? entity.name_en : entity.name_vi;
}
